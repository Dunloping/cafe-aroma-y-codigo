-- Café Aroma & Código
-- Esquema del buzón de contacto y sugerencias.
-- Ejecutar con: npm run db:init

create table if not exists contact_messages (
  id          bigint generated by default as identity primary key,
  motivo      text not null
              check (motivo in ('reserva', 'consulta', 'sugerencia')),
  nombre      text not null
              check (char_length(nombre) between 2 and 80),
  correo      text not null
              check (char_length(correo) <= 120),
  telefono    text
              check (telefono is null or char_length(telefono) <= 30),
  mensaje     text not null
              check (char_length(mensaje) between 10 and 1000),
  estado      text not null default 'nuevo'
              check (estado in ('nuevo', 'leido', 'respondido')),
  ip_hash     text,
  user_agent  text,
  creado_en   timestamptz not null default now()
);

create index if not exists contact_messages_creado_en_idx
  on contact_messages (creado_en desc);

create index if not exists contact_messages_ip_hash_idx
  on contact_messages (ip_hash, creado_en desc);

comment on table contact_messages is
  'Mensajes enviados desde el formulario de contacto y el buzón de sugerencias.';
